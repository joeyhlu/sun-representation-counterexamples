"""Generate SunA157242.lean from the certificate of the counterexample N = 107576474238337.

Usage (from the repository root):
    python lean/gen_lean_a157242.py certificates/A157242_N107576474238337.csv lean/SunA157242.lean

The generator re-checks in Python exactly the finite statement that Lean's kernel is asked to
decide, so a wrong table is caught here before Lean sees it.
"""
import csv
import sys

N = 107576474238337
K = 11
XR, YR = 47, 44                       # 2^47 > N and 11 * 2^44 > N
assert 2 ** XR > N and K * 2 ** YR > N and N % 2 == 1

src, dst = sys.argv[1], sys.argv[2]
dv = [[0] * YR for _ in range(XR)]
for row in csv.reader(open(src)):
    if not row or not row[0].isdigit():
        continue
    x, y, p, pm, d = (int(v) for v in row)
    assert p == N - 2 ** x - K * 2 ** y and pm == p % 6
    dv[x][y] = d

# the statement `key` of the Lean file, for all x < XR and y < YR (x = 0 and y = 0 included)
for x in range(XR):
    for y in range(YR):
        s = 2 ** x + K * 2 ** y
        if N <= s + 1:
            continue
        p = N - s
        d = dv[x][y]
        assert p % 6 != 5 or (1 < d < p and p % d == 0), (x, y)


def table(t):
    return ",\n".join("  [" + ", ".join(str(v) for v in r) + "]" for r in t)


lean = f'''/-
# A counterexample to Zhi-Wei Sun's conjecture in OEIS A157242 (24 February 2009)

Conjecture.  Except for 33, 39, 45, 171 and 247, every odd integer greater than 28 can be
written as `p + 2 ^ x + 11 * 2 ^ y` with `x, y ≥ 1` and `p` a prime congruent to 5 modulo 6.

This file proves that the odd number `{N}` has no such representation.

* Only the Lean 4 core library is used (no Mathlib, no other dependency).
* Primality is defined from scratch below.
* The only large computation is the finite statement `key` ({XR} × {YR} cases), evaluated by
  Lean's kernel (`decide +kernel`), not by compiled code.  The other uses of `decide` are single
  closed arithmetic facts.

Generated by `lean/gen_lean_a157242.py` from `certificates/A157242_N{N}.csv`.
-/

namespace SunA157242

/-- `p` is prime: `p ≥ 2` and the only divisors of `p` are `1` and `p`. -/
def IsPrime (p : Nat) : Prop := 2 ≤ p ∧ ∀ d : Nat, d ∣ p → d = 1 ∨ d = p

/-- `N = p + 2^x + 11 * 2^y` with `x, y ≥ 1` and `p` a prime congruent to 5 modulo 6. -/
def Representable (N : Nat) : Prop :=
  ∃ p x y : Nat, IsPrime p ∧ p % 6 = 5 ∧ 1 ≤ x ∧ 1 ≤ y ∧ N = p + 2 ^ x + 11 * 2 ^ y

/-- The counterexample. -/
abbrev N₀ : Nat := {N}

/-- Row `x` (0..{XR - 1}), column `y` (0..{YR - 1}): a proper divisor of `N₀ - 2^x - 11 * 2^y` when that
number is congruent to 5 modulo 6, and `0` otherwise. -/
def dvTable : List (List Nat) := [
{table(dv)}
]

def dv (x y : Nat) : Nat := (dvTable.getD x []).getD y 0

set_option maxHeartbeats 0 in
/-- The finite check.  For every pair `(x, y)` in range, `N₀ - 2^x - 11 * 2^y` is at most `1`, or
is not congruent to 5 modulo 6, or has the proper divisor `dv x y`. -/
theorem key : ∀ x, x < {XR} → ∀ y, y < {YR} →
    N₀ ≤ 2 ^ x + 11 * 2 ^ y + 1 ∨
    (N₀ - (2 ^ x + 11 * 2 ^ y)) % 6 ≠ 5 ∨
    (1 < dv x y ∧ dv x y < N₀ - (2 ^ x + 11 * 2 ^ y) ∧ (N₀ - (2 ^ x + 11 * 2 ^ y)) % dv x y = 0) := by
  decide +kernel

theorem two_pow_pos (k : Nat) : 0 < 2 ^ k := by
  induction k with
  | zero => decide
  | succ n ih => rw [Nat.pow_succ]; exact Nat.mul_pos ih (by decide)

/-- `N₀` is not of the form `p + 2^x + 11 * 2^y` with `p` a prime congruent to 5 modulo 6.
(The proof does not use `x, y ≥ 1`: there is no representation with `x = 0` or `y = 0` either.) -/
theorem not_representable : ¬ Representable N₀ := by
  intro h
  rcases h with ⟨p, x, y, hp, h6, _, _, hN⟩
  have hN₀ : N₀ = {N} := rfl
  have hp2 : 2 ≤ p := hp.1
  have hxpos : 0 < 2 ^ x := two_pow_pos x
  have hypos : 0 < 2 ^ y := two_pow_pos y
  have hx : x < {XR} := by
    cases Nat.lt_or_ge x {XR} with
    | inl h => exact h
    | inr h =>
      have hpow : 2 ^ {XR} ≤ 2 ^ x := Nat.pow_le_pow_right (by decide) h
      have hval : (2 : Nat) ^ {XR} = {2 ** XR} := by decide
      omega
  have hy : y < {YR} := by
    cases Nat.lt_or_ge y {YR} with
    | inl h => exact h
    | inr h =>
      have hpow : 2 ^ {YR} ≤ 2 ^ y := Nat.pow_le_pow_right (by decide) h
      have hval : (2 : Nat) ^ {YR} = {2 ** YR} := by decide
      omega
  have hps : N₀ - (2 ^ x + 11 * 2 ^ y) = p := by omega
  rcases key x hx y hy with h1 | h5 | ⟨hd1, hd2, hd3⟩
  · omega
  · rw [hps] at h5
    exact h5 h6
  · rw [hps] at hd2 hd3
    have hdvd : dv x y ∣ p := Nat.dvd_of_mod_eq_zero hd3
    cases hp.2 (dv x y) hdvd with
    | inl h => omega
    | inr h => omega

/-- Sun's conjecture in OEIS A157242 is false. -/
theorem sun_A157242_conjecture_false :
    ¬ ∀ N : Nat, N % 2 = 1 → 28 < N → N ≠ 33 → N ≠ 39 → N ≠ 45 → N ≠ 171 → N ≠ 247 →
      Representable N := by
  intro h
  exact not_representable
    (h N₀ (by decide) (by decide) (by decide) (by decide) (by decide) (by decide) (by decide))

end SunA157242

#print axioms SunA157242.sun_A157242_conjecture_false
'''
open(dst, "w", encoding="utf-8", newline="\n").write(lean)
print("wrote", dst, len(lean), "bytes")
